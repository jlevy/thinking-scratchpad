#!/usr/bin/env python3
"""Render frontier/CERTIFICATE-REACH.md: where the fractional certificate can still go.

The instrument has a ceiling that depends only on ``n`` and the direction net --
``ceil(sqrt(n)) / (1 + D)``, derived in ``sqpack.fractional.certificate.ceiling_side``
-- and a second cap that depends on the case: its best known packing, scaled into the
container, refutes every certificate above ``U * max(cos d + sin d) / (1 + D)``, ``d``
running over each tilt's offset from its nearest net direction (`packing_side_cap`,
derived at n = 11 in X-014). The smaller of the two is the ``limit``, and joining it
against the frontier's own bounds answers the question a planner actually has, which
is not "how does the method work" but "which case should the next core run".

Four verdicts come out of the join, and each says something different:

  foreclosed   the limit sits at or below the case's existing lower bound, so no
               certificate of this shape can ever improve it. The ceiling forecloses
               exactly the cases whose value is the grid bound ceil(sqrt(n)), which is
               where the refuting grid of ceil(sqrt(n))^2 B-squares fits; the cap
               forecloses a case whose lower bound already reaches it, which a solved
               case with a tilt inventory always does, since the cap sits strictly
               below its own packing.
  packing      the limit clears the best known packing, so the method is not what
               limits this case: the gap to that packing is the whole prize. Only a
               case with no tilt inventory reads this way, because a cap never clears
               the packing it is built from.
  ceiling      the ceiling lands between the two, so it caps the prize below the gap.
  cap          the packing-side cap lands below the ceiling and between the two.

The figure to rank on is the last column, which is the most a certificate could add
to the case's lower bound. It is an upper bound on the prize and not a forecast: what
a search actually reaches is set by the covering value at that side, which is lower.

A second join adds what the record now shows about that gap between prize and
reach: the packing-limited certificates land within 0.001 of the same fraction of
their cases' best known packings. Ceiling-limited certificates are excluded from that
comparison, because their ratio measures the method's own ceiling rather than a
packing. How many rows are on each side is read from the corpus and never written
down here -- a retained rung that gains enough side moves from one side to the other,
which is what happened when `T-021` raised the n = 20 package to 97/20 and turned a
three-point regularity into a two-point one. The regularity is measured, not proved,
and the document says so plainly where it appears -- see `measured_attainment` and
`predicted_reach` for where the two figures it produces, `ratio` and `predicted`,
come from.

Usage:
    uv run --frozen python -m devtools.render_certificate_reach
    uv run --frozen python -m devtools.render_certificate_reach --check
"""

