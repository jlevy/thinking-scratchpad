# Massaccesi's net, which every retained certificate uses: 181 half-tangents from 0 to
# a rational just above tan(pi/8). D is about T / K, so refining the net raises the
# ceiling only as fast as K grows.
ANGLE_LIMIT = Fraction(207107, 500000)
DIRECTION_STEPS = 180
NET = tuple(ANGLE_LIMIT * k / DIRECTION_STEPS for k in range(DIRECTION_STEPS + 1))


def largest_half_gap_tangent(half_tangents: tuple[Fraction, ...]) -> Fraction:
    """``D`` for a net: the expression `ceiling_side_for_net` takes its supremum over."""
    return max((right - left) / (1 + left * right) for left, right in pairwise(half_tangents))


def net_directions_deg(half_tangents: tuple[Fraction, ...]) -> tuple[float, ...]:
    """Each net direction as the angle, in degrees, its rotation turns through.

    ``sqpack.fractional.model.rotation_from_half_tangent`` turns a half-tangent ``t``
    into the exact rotation by ``2 arctan t``; this is that angle as a float, for the
    one place in this document where a direction is compared against a record's tilt
    rather than decided exactly.
    """
    return tuple(math.degrees(2 * math.atan(tangent)) for tangent in half_tangents)


def fold_tilt(tilt_deg: float) -> float:
    """A tilt reduced to ``[0, 45]`` by the symmetries the net relies on.

    A square is its own image under a quarter turn, so a tilt is read modulo 90; the
    container's diagonal reflection, which ``Condition 1`` makes available, sends
    ``theta`` to ``90 - theta`` and folds ``(45, 90)`` onto ``(0, 45)``. A negative
    tilt folds the same way: ``-36.6`` reads as ``53.4`` modulo 90 and then as
    ``36.6``. The reduction is done in ``Fraction`` so that it is exact; only the
    trigonometry that follows it rounds.
    """
    reduced = Fraction(tilt_deg) % 90
    if reduced > 45:
        reduced = 90 - reduced
    return float(reduced)


def containment_factor(tilt_deg: float, directions_deg: tuple[float, ...]) -> float:
    """``cos d + sin d`` for a tilt's offset ``d`` from the nearest net direction.

    A closed ``B``-square turned by ``d`` from a square of side ``lambda`` fits inside
    it exactly when ``lambda >= B (cos d + sin d)``, and strictly inside when the
    inequality is strict: the containment step behind ``Condition 4``.
    """
    folded = fold_tilt(tilt_deg)
    offset = math.radians(min(abs(folded - direction) for direction in directions_deg))
    return math.cos(offset) + math.sin(offset)


def packing_side_cap(
    upper: float,
    tilts_deg: list[float],
    half_tangents: tuple[Fraction, ...],
    shrink: Fraction | None = None,
) -> float:
    """``U * max(cos d + sin d) / (1 + D)``: where the best known packing refutes the net.

    The grid behind ``ceiling_side`` is one packing, and the case's best known packing
    is another that refutes certificates the same way. Take it at its side ``U`` with
    tilt inventory ``tilts_deg`` and scale it by ``lambda = L / U < 1`` into a
    container of side ``L``. Each scaled square has side ``lambda`` and sits at some
    tilt ``theta``; fold ``theta`` onto the net's arc (`fold_tilt`) and let ``d`` be
    its offset from the nearest net direction. A closed ``B``-square at that net
    direction fits about the same centre exactly when ``lambda >= B (cos d + sin d)``,
    and strictly inside when the inequality is strict. So for
    ``L > U B max(cos d + sin d)``, the maximum over the inventory, the scaled packing
    holds ``n`` pairwise disjoint closed ``B``-squares at net directions; ``Condition 5``
    gives each mass at least ``1``, the total is at least ``n``, and ``Condition 2``
    forbids that. No certificate with shrink ``B`` exists above that side, whatever
    its atoms and weights.

    With ``shrink`` given, that side is the value returned. Without it, ``Condition 4``'s
    ``B < 1 / (1 + D)`` is taken to its supremum, as `ceiling_side_for_net` does over
    `ceiling_side`, and the result is ``U max(cos d + sin d) / (1 + D)``: a supremum
    that no certificate attains, and always strictly below ``U``, because ``d`` never
    exceeds the half-gap while ``cos d + sin d < 1 + tan d`` past ``d = 0``. The
    argument is X-014's (``campaign/explorations/X-014-closing-from-both-ends.md``),
    made at ``n = 11``.

    The record's side and tilts are floats and so is the trigonometry; the net, the
    shrink and the final product are exact. An inventory of ``[0]`` has factor exactly
    ``1``, so a grid packing at side ``ceil(sqrt(n))`` returns `ceiling_side_for_net`'s
    value bit for bit.
    """
    if not tilts_deg:
        raise ValueError("a packing's tilt inventory cannot be empty")
    if shrink is not None and shrink <= 0:
        raise ValueError(f"shrink {shrink} is not positive")
    directions = net_directions_deg(half_tangents)
    factor = Fraction(max(containment_factor(tilt, directions) for tilt in tilts_deg))
    if shrink is None:
        shrink = 1 / (1 + largest_half_gap_tangent(half_tangents))
    return float(Fraction(upper) * shrink * factor)


def case_record(path: pathlib.Path) -> dict:
    """The ``packing`` block of one frontier file's front matter."""
    document = load_yaml(path.read_text(encoding="utf-8").split("---\n")[1])
    return document["packing"]


def tilt_inventory(reported_upper: dict | None) -> list[float] | None:
    """``tilt_angles_deg`` from a ``reported_upper_bound`` block, as floats.

    The list holds the distinct tilts of the best known packing in degrees, signed as
    the geometry was imported (n = 17 carries ``-36.62...``); ``null`` means no
    geometry was imported, and reads as ``None`` here so that no cap is invented.
    """
    if reported_upper is None or reported_upper.get("tilt_angles_deg") is None:
        return None
    return [float(tilt) for tilt in reported_upper["tilt_angles_deg"]]


def cases() -> list[dict]:
    """One row per frontier case with a verified lower bound, verdict included.

    ``bound`` names which of ``ceiling`` and ``cap`` is the ``limit`` -- ``cap`` only
    where it sits strictly below the ceiling, so a grid packing whose cap equals its
    ceiling reads ``ceiling`` -- and ``verdict`` reads the limit against the case's
    own two bounds.
    """
    rows = []
    for path in sorted(FRONTIER.glob("n-*.md")):
        n = int(path.stem.split("-")[1])
        record = case_record(path)
        lower = record.get("verified_lower_bound")
        if not lower or lower.get("value") is None:
            continue
        low = float(lower["value"])
        upper = record.get("reported_upper_bound")
        up = float(upper["value"]) if upper and upper.get("value") is not None else None
        tilts = tilt_inventory(upper)
        ceiling = float(ceiling_side_for_net(n, NET))
        cap = packing_side_cap(up, tilts, NET) if up is not None and tilts is not None else None
        if cap is not None and cap < ceiling:
            bound, limit = "cap", cap
        else:
            bound, limit = "ceiling", ceiling
        if limit <= low:
            verdict, prize = "foreclosed", 0.0
        elif up is not None and limit >= up:
            # Clamped because the two endpoints are parsed from different records: a
            # case whose packing sits exactly at its lower bound must read +0.0000,
            # never a negative zero from the last bit of a float subtraction.
            verdict, prize = "packing", max(up - low, 0.0)
        else:
            verdict, prize = bound, max(limit - low, 0.0)
        rows.append(
            {
                "n": n,
                "order": grid_refutation_order(n),
                "lower": low,
                "upper": up,
                "tilts": tilts,
                "ceiling": ceiling,
                "cap": cap,
                "limit": limit,
                "bound": bound,
                "verdict": verdict,
                "prize": prize,
            }
        )
    return rows


def load_certificate(path: pathlib.Path) -> tuple[dict, Fraction]:
    """A certificate record and the mass recomputed from its own atoms.

    The recomputation is the point: a certificate's mass is what its atoms sum to,
    and the stored ``total_mass`` field is a convenience that can go stale against
    them. Here it is checked rather than trusted, because every figure this document
    keys off that mass -- which case a certificate moves first (`least_size_certified`),
    and the feasible masses the reported-value table quotes -- would be wrong together
    if the field and the atoms ever disagreed. `devtools.check_rung_figures` makes the
    same check for the figures the results register quotes; this is the same rule at
    the one other place the mass is read.
    """
    record = json.loads(path.read_text())
    total_mass = Fraction(str(record["total_mass"]))
    atom_mass = sum((Fraction(str(atom[2])) for atom in record["atoms"]), Fraction())
    if atom_mass != total_mass:
        try:
            display = path.relative_to(ROOT)
        except ValueError:
            display = path
        raise ValueError(
            f"{display}: declared total_mass {total_mass} does not equal atom sum {atom_mass}"
        )
    return record, atom_mass


def covering_value_register() -> list[dict]:
    """The rows of ``frontier/covering-values.yaml``, in register order.

    One row per ``(n, side, site set)``: what the record reports for the restricted
    covering program, with ``converged`` a field rather than a phrase. The objectives
    are quotations -- from `results.yaml`'s own accounts of T-018, T-019 and T-020,
    from agenda-019's target list, and from X-013's confirmation of six of them -- and
    nothing here can recompute them: no covering-search run log or solver checkpoint
    was retained for any of them. What can be recomputed is the certificate frozen at
    that side, where one is, and that is a feasible mass rather than an optimum.
    """
    document = load_yaml(COVERING_VALUES.read_text(encoding="utf-8"))
    return document["values"]


def reported_covering_values() -> list[dict]:
    """The register's rows, with each frozen artifact's atom count and mass recomputed.

    The masses are read out of the frozen JSON at render time rather than written into
    the table by hand, so no row can quote a figure the artifact beside it does not
    have. A path that no longer resolves raises rather than rendering a blank cell:
    this table's subject is what the repository retains, and a vanished artifact is a
    change to that answer, not a missing detail. ``mass`` is that recomputed mass, or
    ``None`` where nothing was frozen.
    """
    out = []
    for row in covering_value_register():
        artifact = row["frozen_artifact"]
        mass = None
        if artifact is None:
            evidence = f"nothing frozen here. {row['notes']}"
        else:
            record, mass = load_certificate(REPO / artifact)
            evidence = (
                f"frozen {len(record['atoms']):,}-atom certificate, "
                f"feasible mass {float(mass):.6f}. {row['notes']}"
            )
        out.append(
            {
                "n": row["n"],
                "side": row["side_decimal"],
                "exact_side": Fraction(row["side"]),
                "site_set": row["site_set"],
                "reported": row["objective"],
                "converged": row["converged"],
                "stop_reason": row["stop_reason"],
                "mass": mass,
                "evidence": evidence,
            }
        )
    return out


def sides_named(sides: list[str]) -> str:
    """``3.96``, ``4.58`` and ``4.59``: a list of sides as the prose quotes them."""
    quoted = [f"`{side}`" for side in sides]
    if len(quoted) <= 1:
        return "".join(quoted)
    return ", ".join(quoted[:-1]) + " and " + quoted[-1]


def retained_certificates() -> list[dict]:
    """Every retained first-party certificate, found by globbing the case packages.

    A case package's own ``__main__.py`` always replays ``certificate.json`` as the
    rung currently in force -- every package's ``replay.py`` sets
    ``CERTIFICATE_PATH = Path(__file__).with_name("certificate.json")``, and a
    package that also keeps a weaker historical rung stores it under a different
    filename (``certificate-<side>.json``), never this one. So globbing straight to
    that filename, rather than importing each package's Python, finds exactly the
    rungs the register currently holds.

    The row is keyed by ``least_size_certified``, not by the JSON's own ``n`` field.
    Condition 2 of the certificate mentions only ``n``, so a certificate of mass ``M``
    certifies every integer above ``M``, and the case it moves first is the least of
    them -- which need not be the ``n`` the package is named for. The n = 20 package
    is the worked example in both directions: while its retained rung was the 24/5
    one, mass 946131/50000 = 18.922620, this document keyed it to ``n = 19``; the
    97/20 rung that replaced it has mass 19848723/1000000 = 19.848723 and keys it to
    ``n = 20``. Nothing here depends on which of those is current.
    """
    rows = []
    for path in sorted(CASES.glob("n*_fractional_certificate/certificate.json")):
        record, total_mass = load_certificate(path)
        outer_side = Fraction(str(record["outer_side"]))
        rows.append(
            {
                "package": path.parent.name,
                "n": least_size_certified(total_mass),
                "lower": float(outer_side),
            }
        )
    return rows


def measured_attainment(rows: list[dict]) -> list[dict]:
    """Join every retained certificate against its case's ceiling and best packing.

    ``rows`` is `cases`'s output. A retained certificate's own target ``n`` (from
    `retained_certificates`) picks the row that carries its ceiling and best known
    packing, exactly as every other figure in this document is derived rather than
    looked up by hand. ``binds`` names whichever of the two is the tighter cap, and
    ``ratio`` is the retained lower bound divided by that binding value -- against
    the best packing where the packing binds, against the ceiling where it does not.
    """
    by_n = {row["n"]: row for row in rows}
    out = []
    for cert in retained_certificates():
        case = by_n[cert["n"]]
        best_packing = case["upper"]
        ceiling = case["ceiling"]
        lower = cert["lower"]
        if best_packing is None:
            raise ValueError(f"n = {cert['n']}: retained certificate has no best packing")
        if ceiling >= best_packing:
            binds, ratio = "packing", lower / best_packing
        else:
            binds, ratio = "ceiling", lower / ceiling
        out.append(
            {
                "n": cert["n"],
                "package": cert["package"],
                "lower": lower,
                "best_packing": best_packing,
                "ceiling": ceiling,
                "binds": binds,
                "ratio": ratio,
            }
        )
    return sorted(out, key=lambda r: r["n"])


